<?php

declare(strict_types=1);

namespace Selyusize\EventsRouter\Dispatch;

/**
 * Как рассылка реагирует на ошибку слушателя.
 */
enum ErrorStrategy
{
    /**
     * Передать ошибку обработчику и продолжить: остальные слушатели будут вызваны.
     * Стратегия по умолчанию.
     */
    case Continue;

    /**
     * Передать ошибку обработчику и остановиться: оставшиеся слушатели получат статус Skipped.
     */
    case Stop;

    /**
     * Не перехватывать: исключение выходит из dispatch() к вызывающему коду,
     * обработчик ошибок не вызывается. Для тестов и случаев, когда снаружи транзакция.
     */
    case Throw;
}
